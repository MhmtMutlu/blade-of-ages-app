#!/usr/bin/env python3
"""Copies what the realm pages need from the game repository into data/game.json.

The game is the single source of realm facts: maps, enemies, elite, boss phases, realm weapon, armour set and myth
power, with their texts in every language the game ships. The site keeps a copy so it builds without the game repo;
build.py compares the copy with the game when the repo is next to it and fails when they drift.

    python3 scripts/sync-game.py          # game repo at ../blades-of-ages, or AOB_GAME_REPO
"""
import json, os, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
GAME = pathlib.Path(os.environ.get("AOB_GAME_REPO", ROOT.parent / "blades-of-ages"))
OUT = ROOT / "data" / "game.json"
# Site language → the game's l10n file
LANGS = {"tr": "tr", "en": "en", "ja": "ja", "ko": "ko", "zh-Hant": "zh-Hant", "de": "de", "fr": "fr"}


def snapshot(game: pathlib.Path) -> dict:
    data = game / "data"
    load = lambda n: json.loads((data / n).read_text(encoding="utf-8"))
    realms = load("realms.json")["realms"]
    bosses = {b["id"]: b for b in load("bosses.json")["bosses"]}
    weapons = {w["id"]: w for w in load("weapons.json")["realmWeapons"]}
    powers = {p["realm"]: p for p in load("myth-powers.json")["byRealm"]}
    eras = load("eras.json")["eras"]
    out_realms, keys = [], []
    for r in realms:
        boss = bosses.get(r["boss"], {})  # realms still being drawn have no boss data yet
        power = powers.get(r["id"])
        out_realms.append({
            "id": r["id"], "era": r["era"], "maps": r["maps"], "enemies": r["enemies"], "elite": r["elite"],
            "boss": r["boss"], "weapon": r["weapon"], "armorSet": r["armorSet"], "mythPower": power and power["id"],
            "phases": [p.get("hp", "") for p in boss.get("phases", [])], "rewards": len(boss.get("rewards", [])),
        })
        keys += [f"content.realms.{r['id']}.{k}" for k in ("name", "mapName", "mythology", "rule")]
        for e in r["enemies"] + [r["elite"]]:
            keys += [f"content.enemies.{e}.{k}" for k in ("name", "role", "behavior", "teaches")]
        keys += [f"content.bosses.{r['boss']}.{k}" for k in ("name", "lore")]
        for i in range(len(boss.get("phases", []))):
            keys += [f"content.bosses.{r['boss']}.phases.{i}.{k}" for k in ("name", "text", "counter")]
        keys += [f"content.bosses.{r['boss']}.rewards.{i}" for i in range(len(boss.get("rewards", [])))]
        if r["weapon"] in weapons:
            keys += [f"content.weapons.{r['weapon']}.{k}" for k in ("name", "behavior")]
        keys += [f"content.armor-sets.{r['armorSet']}.{k}" for k in ("name", "bonus2", "bonus4")]
        if power:
            keys += [f"content.myth-powers.{power['id']}.{k}" for k in ("name", "effect")]
    keys += [f"content.eras.{e['id']}.{k}" for e in eras for k in ("name", "period")]
    text = {}
    for site_lang, game_lang in LANGS.items():
        l10n = json.loads((data / "l10n" / f"{game_lang}.json").read_text(encoding="utf-8"))
        text[site_lang] = {k.removeprefix("content."): l10n[k] for k in keys if k in l10n}
    return {"_doc": "Generated by scripts/sync-game.py from the game repository. Do not edit by hand.",
            "realms": out_realms, "text": text}


def main() -> None:
    if not (GAME / "data").is_dir():
        sys.exit(f"Game repo not found: {GAME} (set AOB_GAME_REPO)")
    snap = snapshot(GAME)
    OUT.write_text(json.dumps(snap, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    missing = {l: sum(1 for _ in snap["text"]["en"]) - len(t) for l, t in snap["text"].items()}
    print(f"{OUT.relative_to(ROOT)}: {len(snap['realms'])} realms; texts missing per language: {missing}")


if __name__ == "__main__":
    main()
